import assert from 'node:assert/strict';
import test from 'node:test';

import { createGhPullRequestClient } from '../src/coordinator-github-side-effects.mjs';
import { createPrOwnershipLoop } from '../src/pr-ownership-loop.mjs';
import { createRunEventLog } from '../src/run-evidence.mjs';

test('PR ownership loop schedules a same-lineage repair run when CI fails', async () => {
  const comments = [];
  const runEvents = createRunEventLog({
    async appendText() {},
    now: (() => {
      const times = [
        '2026-06-23T23:55:00.000Z',
        '2026-06-23T23:56:00.000Z',
      ];
      return () => times.shift() ?? '2026-06-23T23:57:00.000Z';
    })(),
  });
  const loop = createPrOwnershipLoop({
    issueClient: {
      async createComment(comment) {
        comments.push(comment);
        return { url: `https://github.com/justbill2020/Lambchop/issues/${comment.issueNumber}#repair` };
      },
    },
    pullRequestClient: {
      async viewPullRequest({ repository, number }) {
        assert.equal(repository, 'justbill2020/Lambchop');
        assert.equal(number, 90);
        return {
          number: 90,
          url: 'https://github.com/justbill2020/Lambchop/pull/90',
          state: 'OPEN',
          mergeStateStatus: 'UNSTABLE',
          reviewDecision: '',
          statusCheckRollup: [
            {
              name: 'test',
              status: 'COMPLETED',
              conclusion: 'FAILURE',
              detailsUrl: 'https://github.com/justbill2020/Lambchop/actions/runs/1',
            },
          ],
        };
      },
    },
    runEventLog: runEvents,
  });

  const result = await loop.observePullRequest({
    repository: 'justbill2020/Lambchop',
    issueNumber: 40,
    runId: 'run-40',
    pullRequestNumber: 90,
  });

  assert.equal(result.status, 'repair-scheduled');
  assert.deepEqual(result.repair, {
    run_id: 'run-40-repair-1',
    parent_run_id: 'run-40',
    issue_number: 40,
    pull_request: {
      number: 90,
      url: 'https://github.com/justbill2020/Lambchop/pull/90',
    },
    reason: 'ci-failed',
    summary: 'CI check failed: test.',
  });
  assert.deepEqual(runEvents.events().map((event) => event.type), [
    'pr.observed',
    'repair.scheduled',
  ]);
  assert.equal(comments.length, 1);
  assert.match(comments[0].body, /^> \*This was generated by AI during triage\.\*/);
  assert.match(comments[0].body, /## Repair scheduled/);
  assert.match(comments[0].body, /CI check failed: test/);
});

