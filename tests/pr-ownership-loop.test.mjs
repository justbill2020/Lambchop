test('production PR client reads CI and review state through gh pr view', async () => {
  const ghCalls = [];
  const client = createGhPullRequestClient({
    async runGh(args) {
      ghCalls.push(args);
      return JSON.stringify({
        number: 92,
        url: 'https://github.com/justbill2020/Lambchop/pull/92',
        state: 'OPEN',
        mergeStateStatus: 'CLEAN',
        reviewDecision: 'APPROVED',
        statusCheckRollup: [],
      });
    },
  });

  const pr = await client.viewPullRequest({
    repository: 'justbill2020/Lambchop',
    number: 92,
  });

  assert.deepEqual(ghCalls, [[
    'pr',
    'view',
    '92',
    '--repo',
    'justbill2020/Lambchop',
    '--json',
    'number,url,state,mergedAt,mergeStateStatus,reviewDecision,statusCheckRollup',
  ]]);
  assert.equal(pr.mergeStateStatus, 'CLEAN');
  assert.equal(pr.reviewDecision, 'APPROVED');
});

