function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function countStatuses(workItems) {
  const counts = {
    todo: 0,
    in_progress: 0,
    blocked: 0,
    done: 0,
    skipped: 0,
  };

  for (const item of workItems) {
    if (counts[item.status] !== undefined) {
      counts[item.status] += 1;
    }
  }

  return counts;
}

export function createRunEvidence() {
  const ledger = [];

  return {
    append(event) {
      ledger.push(clone(event));
    },

    entries() {
      return clone(ledger);
    },

    projectDashboard({ project, workItems, nextAction, projectFloor = null }) {
      const counts = countStatuses(workItems);
      const latestEvents = [...ledger].sort((left, right) => right.at.localeCompare(left.at));
      const completedRun = latestEvents.find((event) => event.type === 'run_completed') ?? null;
      const validationEvent = latestEvents.find((event) => event.type === 'validation_passed') ?? null;

      return {
        project: clone(project),
        ...(projectFloor ? { projectFloor: clone(projectFloor) } : {}),
        summary: {
          ...counts,
          proposals_need_review: 0,
          active_parallel_lanes: 0,
          next_action: nextAction,
        },
        active_lanes: [],
        latest_progress: latestEvents.map((event) => `${event.at}: ${event.summary}`),
        last_run: completedRun
          ? {
              run_id: completedRun.runId,
              active_work_item: completedRun.storyKey ?? null,
              summary: completedRun.summary,
              validation: validationEvent?.summary ?? '',
            }
          : null,
      };
    },
  };
}

const RUN_EVENT_TYPES = new Set([
  'selection',
  'assignment',
  'sandbox',
  'worker.started',
  'worker.completed',
  'files.changed',
  'validation.passed',
  'validation.failed',
  'comment',
  'pr',
  'pr.observed',
  'pr.merge-ready',
  'repair.scheduled',
  'blocker',
  'feedback',
  'completion',
  'handoff',
]);

function defaultNow() {
  return new Date().toISOString();
}

function normalizeRunEvent(event, { sequence, now }) {
  if (!event?.runId) {
    throw new Error('runId is required');
  }
  if (!RUN_EVENT_TYPES.has(event.type)) {
    throw new Error(`Unsupported run event type: ${event.type}`);
  }
  if (!event.summary) {
    throw new Error('summary is required');
  }

  const normalized = {
    sequence,
    at: event.at ?? now(),
    run_id: event.runId,
    type: event.type,
    summary: event.summary,
  };

  if (event.changedFiles) {
    normalized.changed_files = [...event.changedFiles];
  }
  if (event.validation) {
    normalized.validation = clone(event.validation);
  }
  if (event.blocker) {
    normalized.blocker = clone(event.blocker);
  }
  if (event.workLogEntry) {
    normalized.work_log_path = `runs/${event.runId}/work-log.md`;
  }

  return normalized;
}

function latestEvent(events) {
  return [...events].sort((left, right) => right.sequence - left.sequence)[0] ?? null;
}

function uniqueChangedFiles(events) {
  return [...new Set(events.flatMap((event) => event.changed_files ?? []))];
}

function latestValidation(events) {
  return [...events]
    .sort((left, right) => right.sequence - left.sequence)
    .find((event) => event.validation?.status)?.validation ?? null;
}

export function createRunEventLog(options = {}) {
  const now = options.now ?? defaultNow;
  const appendText = options.appendText ?? (async () => {});
  const events = [];

  return {
    async append(event) {
      const normalized = normalizeRunEvent(event, {
        sequence: events.length + 1,
        now,
      });
      events.push(normalized);

      if (event.workLogEntry) {
        await appendText(
          normalized.work_log_path,
          `- ${normalized.at}: ${event.workLogEntry}\n`,
        );
      }

      return clone(normalized);
    },

    events() {
      return clone(events);
    },

    summarizeForIssueComment({ runId }) {
      const runEvents = events.filter((event) => event.run_id === runId);
      const latest = latestEvent(runEvents);
      const validation = latestValidation(runEvents);
      const changedFiles = uniqueChangedFiles(runEvents);
      const blockers = runEvents.filter((event) => event.type === 'blocker');
      const workLogEvent = runEvents.find((event) => event.work_log_path);

      return [
        '> *This was generated by AI during triage.*',
        '',
        `## Run ${runId} Summary`,
        '',
        `- Events: ${runEvents.length}`,
        `- Latest status: ${latest?.summary ?? 'No events recorded.'}`,
        `- Validation: ${validation?.status ?? 'not recorded'}`,
        `- Changed files: ${changedFiles.length ? changedFiles.join(', ') : 'none'}`,
        `- Blockers: ${blockers.length}`,
        `- Work log: ${workLogEvent?.work_log_path ?? 'not recorded'}`,
      ].join('\n');
    },

    sessionAnalytics({ runId }) {
      const runEvents = events.filter((event) => event.run_id === runId);
      const changedFiles = uniqueChangedFiles(runEvents);
      const blockers = runEvents.filter((event) => event.type === 'blocker');
      const validation = latestValidation(runEvents);

      return {
        run_id: runId,
        event_count: runEvents.length,
        blocker_count: blockers.length,
        changed_file_count: changedFiles.length,
        validation_status: validation?.status ?? 'not recorded',
        churn_signals: {
          repeated_blockers: blockers.length,
          changed_files: changedFiles.length,
        },
      };
    },
  };
}
